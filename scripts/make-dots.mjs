// Generates src/landdots.js: an evenly spread set of points on land, packed as Int16 (lat, lon) × 10.
// The globe draws these as dots; no map library is needed in the page. Run once: node scripts/make-dots.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url), 'utf8'));
const land = feature(topo, topo.objects.land);

const N = 16000; // Fibonacci sphere samples; roughly 29% land
const golden = Math.PI * (3 - Math.sqrt(5));
const pts = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;         // -1..1
  const r = Math.sqrt(1 - y * y);
  const theta = golden * i;
  const x = Math.cos(theta) * r, z = Math.sin(theta) * r;
  const lat = Math.asin(y) * 180 / Math.PI;
  const lon = Math.atan2(z, x) * 180 / Math.PI;
  if (lat < -58) continue; // skip Antarctica's bulk; it only distracts at the globe's bottom
  if (geoContains(land, [lon, lat])) pts.push([lat, lon]);
}
const buf = new Int16Array(pts.length * 2);
pts.forEach(([lat, lon], i) => { buf[i * 2] = Math.round(lat * 10); buf[i * 2 + 1] = Math.round(lon * 10); });
const b64 = Buffer.from(buf.buffer).toString('base64');
writeFileSync(new URL('../src/landdots.js', import.meta.url),
  `/* ${pts.length} land points from world-atlas land-110m (Natural Earth, public domain), Fibonacci-spread; Int16 lat,lon × 10, base64. Generated by scripts/make-dots.mjs */\nconst LAND_DOTS_B64 = "${b64}";\n`);
console.log(pts.length, 'land dots,', Math.round(b64.length / 1024), 'KB');
